//! Buu's Fury game-mechanics tables, read straight from the ROM (no emulator).
//!
//! [`build`] produces one *document* per research file, with exactly the structure of the JSON in the
//! repository's `data/buu/` and `data/battle/buu_ai_extra.json` (the parity references); [`extract`] splits the
//! documents into the per-id content files described in `engine/docs/tables.md`, and
//! [`content::reassemble`] inverts that split (used by the parity tests). Values that are not in the ROM
//! (documentation, emulator measurements, curated names / registries) come from the embedded annotation files
//! in `data/` (generated by `re/dump_annotations.py`) and keep their status tags.

pub mod ai;
pub mod ai_extra;
pub mod bosses;
pub mod characters;
pub mod content;
pub mod diff;
pub mod enemies;
pub mod items;
pub mod script;
pub mod skills;
pub mod util;

pub use content::Docs;
use serde_json::Value;
use util::Ctx;
use wf_rom::{content::Content, Rom};

/// All documents, keyed by reference path relative to the repository's `data/` (e.g. `buu/enemies.json`).
pub fn build(rom: &Rom) -> Docs {
    let c = Ctx::new(rom);
    let mut d = Docs::new();
    d.insert("buu/levels.json".into(), characters::levels(&c));
    d.insert("buu/rng.json".into(), characters::rng(&c));
    d.insert("buu/formulas.json".into(), characters::formulas(&c));
    d.insert("buu/characters.json".into(), characters::characters(&c));
    d.insert("buu/moves.json".into(), skills::moves(&c));
    d.insert("buu/attacks_detail.json".into(), skills::attacks(&c));
    d.insert("buu/items.json".into(), items::items(&c));
    let en = enemies::enemies(&c);
    let names: Vec<Value> = en["enemies"].as_array().unwrap().iter().map(|e| e["name"].clone()).collect();
    let ai = ai::enemy_ai(&c, &names);
    d.insert("buu/bosses.json".into(), bosses::bosses(&en, &ai));
    let main: std::collections::BTreeSet<u32> = ai.trees.keys().copied().collect();
    d.insert("battle/buu_ai_extra.json".into(), ai_extra::ai_extra(&c, &main));
    d.insert("buu/enemies.json".into(), en);
    d.insert("buu/enemy_ai.json".into(), ai.doc);
    d
}

/// Write the table files (`characters/`, `enemies/`, `ai/`, ...) into `out` (paths relative to the content root).
pub fn extract(rom: &Rom, out: &mut Content) -> wf_rom::Result<()> {
    let docs = build(rom);
    let strings = wf_rom::text::StringTable::load(rom).strings;
    content::split(&docs, &strings, out);
    Ok(())
}
