"""Snapshot the script-native arities/names (engine/annotations/script_natives.json, maintained by the script-VM
research) into crates/wf-world/src/natives_gen.rs, used by wf-world's constant-argument scanner.

    .venv/bin/python engine/tools/make_world_natives.py
"""
import json
from pathlib import Path

ENGINE = Path(__file__).resolve().parents[1]
src = json.loads((ENGINE / 'annotations' / 'script_natives.json').read_text())
rows = []
for n in sorted(src, key=lambda n: n['id']):
    rows.append(f'    ({n["id"]:#04x}, {int(n["pops"])}, {int(n["pushes"])}, {json.dumps(n["name"])}),')
out = ('//! GENERATED by engine/tools/make_world_natives.py from engine/annotations/script_natives.json — do not edit.\n'
       '//! (native id, pops, pushes, name)\n'
       'pub const NATIVES: &[(u8, u8, u8, &str)] = &[\n' + '\n'.join(rows) + '\n];\n')
(ENGINE / 'crates' / 'wf-world' / 'src' / 'natives_gen.rs').write_text(out)
print(len(rows), 'natives')
